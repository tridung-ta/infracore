/* Live reports: no polling. Chart tables and server definitions share one response. */
(() => {
 'use strict';
 if(document.body.dataset.mode!=='live')return;
 const $=id=>document.getElementById(id),panel=$('dashboard-live-panel');
  if(!panel)return;
 const tiers={replace:'Thay thế',watch:'Theo dõi',normal:'Bình thường',missing:'Chưa đủ dữ liệu'};
 let view='',page=1,sequence=0,request,exportRequest,documentData,applied={},charts=[],observers=[],busy=false,badgeLoaded=false,badgeRequest;
 const node=(tag,text)=>{const n=document.createElement(tag);
  if(text!==undefined)n.textContent=String(text);
  return n;
  };
 const role=()=>window.itaLiveContext?.user?.role;
 function dispose(){charts.forEach(c=>c.dispose());
  charts=[];
  observers.forEach(o=>o.disconnect());
  observers=[];
  }
 function table(headers,rows,caption){const wrap=node('div');
  wrap.className='dash-table';
  wrap.tabIndex=0;
  wrap.setAttribute('role','region');
  wrap.setAttribute('aria-label',caption);
  const t=node('table');
  t.append(node('caption',caption));
  const head=node('thead'),tr=node('tr');
  headers.forEach(h=>{const th=node('th',h);
  th.scope='col';
  tr.append(th);
  });
  head.append(tr);
  t.append(head);
  const body=node('tbody');
  for(const row of rows){const r=node('tr');
  row.forEach(v=>r.append(node('td',v??'Chưa ghi nhận')));
  body.append(r);
  }if(!rows.length){const r=node('tr'),td=node('td','Không có kết quả phù hợp.');
  td.colSpan=headers.length;
  r.append(td);
  body.append(r);
  }t.append(body);
  wrap.append(t);
  return wrap;
  }
 function bell(n){$('dash-bell-label').textContent=n+' cảnh báo hiệu lực';
  $('nav-alert-count').textContent=String(n);
  $('notification-button').setAttribute('aria-label',`${n} cảnh báo đang hiệu lực, không phải chưa đọc`);
  $('notification-button').title=`${n} cảnh báo đang hiệu lực`;
  $('notification-button').querySelector('.notification-dot').hidden=n===0;
  }
 function chart(title,names,values,headers,rows){const card=node('section');
  card.className='dash-chart-card';
  card.append(node('h3',title));
  const canvas=node('div');
  canvas.className='dash-chart';
  canvas.setAttribute('role','img');
  canvas.setAttribute('aria-label',title+'; bảng đối chiếu bên dưới');
  card.append(canvas,table(headers,rows,title));
  $('dash-output').append(card);
  if(!window.echarts){canvas.textContent='Không tải được biểu đồ. Dùng bảng đối chiếu bên dưới.';
  return;
  }const c=echarts.init(canvas,null,{renderer:'svg'});
  charts.push(c);
  const color=getComputedStyle(document.documentElement);
  c.setOption({animation:false,textStyle:{color:color.getPropertyValue('--ita-text').trim()},legend:headers.length===6?{top:0,textStyle:{color:color.getPropertyValue('--ita-text').trim()}}:undefined,grid:{left:65,right:25,top:headers.length===6?45:25,bottom:70},xAxis:{type:'category',data:names,axisLabel:{interval:0,rotate:20}},yAxis:{type:'value',min:0},series:headers.length===6?['in_use','maintenance','broken','retired'].map((status,i)=>({name:headers[i+2],type:'bar',stack:'status',barMaxWidth:60,data:rows.map(r=>r[i+2]),itemStyle:{color:color.getPropertyValue(['--ita-success','--ita-warning','--ita-danger','--ita-text-muted'][i]).trim()}})):[{type:'bar',data:values,barMaxWidth:60,itemStyle:{color:color.getPropertyValue('--ita-accent').trim()}}]});
  const o=new ResizeObserver(()=>c.resize());
  o.observe(canvas);
  observers.push(o);
  }
 function overview(d){bell(d.alerts_total);
  const grid=node('div');
  grid.className='kpi-grid';
  const s=d.summary;
  for(const [name,value] of [['Sổ tài sản',s.total],['Đang quản lý (không thanh lý)',s.managed],['Tỷ lệ lỗi · '+s.failed_assets+'/'+s.analyzed,s.fault_rate===null?'Chưa có mẫu số':(100*s.fault_rate).toFixed(1)+'%'],['Đề xuất thay thế',s.replace]]){const card=node('article');
  card.className='kpi';
  card.append(node('span',name),node('strong',value));
  grid.append(card);
  }$('dash-output').append(grid,node('p','Tỷ lệ lỗi: phần cứng chưa thanh lý có ít nhất một phiếu repair mở trong 12 tháng lịch / phần cứng đang phân tích. Sổ tài sản gồm cả thanh lý.'));
  if(d.config?.using_defaults)$('dash-output').append(node('p','Đang dùng giá trị mặc định'));
  const g=d.groups;
  }
 function render(d){dispose();
  $('dash-output').replaceChildren();
  documentData=d;
  page=d.page??1;
  $('dash-time').textContent='Số liệu tại '+new Date(d.as_of).toLocaleTimeString('vi-VN',{timeZone:'Asia/Ho_Chi_Minh',hour:'2-digit',minute:'2-digit'})+' · '+new Date(d.as_of).toLocaleDateString('vi-VN',{timeZone:'Asia/Ho_Chi_Minh'})+' · giờ Việt Nam';
  if(view==='overview'&&role()!=='support_technician'){overview(d);
  }else if(view==='alerts'){bell(d.active_total);
  $('dash-output').append(node('p',`${d.total} kết quả khớp / ${d.active_total} cảnh báo đang hiệu lực. Chuông không phải số chưa đọc hoặc số dòng đang lọc.`),table(['Mức độ','Mã','Đối tượng','Lý do'],d.rows.map(r=>[r.level==='critical'?'Nghiêm trọng':'Cần theo dõi',r.code,r.name,r.title]),'Cảnh báo trong phạm vi'));
  }else{$('dash-output').append(node('p',d.source),node('p',`Số dòng dữ liệu: ${d.data_count}. Thiếu dữ liệu: ${d.missing??0}.`));
  if(d.using_defaults)$('dash-output').append(node('p','Đang dùng giá trị mặc định'));
  $('dash-output').append(table(d.headers,d.rows,'Báo cáo trong phạm vi'));
  }$('dash-pagination').hidden=d.page===undefined;
  $('dash-page').textContent=`Trang ${d.page??1} / ${Math.max(1,Math.ceil((d.total??0)/(d.per_page??20)))}`;
  $('dash-previous').disabled=(d.page??1)<=1;
  $('dash-next').disabled=(d.page??1)*(d.per_page??20)>=(d.total??0);
  $('dash-export').hidden=view!=='reports'||role()==='support_technician';
  }
 function filters(){const input={department_id:$('dash-department').value,group:$('dash-group').value};
  if(view==='reports'){input.report=$('dash-report').value;
  if(input.report==='budget'){input.year=$('dash-year').value;
  if($('dash-plan').value)input.plan_id=$('dash-plan').value;
  }}if(role()==='support_technician')input.report='maintenance';
  return input;
  }
 async function load(){if(!role())return;
  const id=++sequence;
  exportRequest?.abort();
  $('dash-previous').disabled=$('dash-next').disabled=true;
  dispose();
  request?.abort();
  request=new AbortController();
  const action=view==='alerts'?'alerts':view==='reports'||role()==='support_technician'?'report-preview':'dashboard';
  const query=new URLSearchParams({op:'ita',act:action,...applied,page:String(page)});
  $('dash-output').setAttribute('aria-busy','true');
  $('dash-message').textContent='Đang tải…';
  $('dash-export').hidden=true;
  try{const r=await fetch('/admin.php?'+query,{signal:request.signal,cache:'no-store'});
  const result=await r.json();
  if(!r.ok||!result.success)throw Error(result.message||'Chưa tải được số liệu.');
  if(id!==sequence)return;
  render(result.data);
  $('dash-message').textContent='Đã tải số liệu. Không tự làm mới.';
  }catch(e){if(id===sequence&&e.name!=='AbortError')$('dash-message').textContent=(e instanceof SyntaxError?'Máy chủ trả phản hồi không hợp lệ.':e.message)+' Dữ liệu cũ (nếu có) giữ nguyên mốc; bấm Làm mới để thử lại.';
  }finally{if(id===sequence)$('dash-output').setAttribute('aria-busy','false');
  }}
 async function initialBell(){if(badgeLoaded||role()==='support_technician')return;
  badgeLoaded=true;
  badgeRequest=new AbortController();
  try{const r=await fetch('/admin.php?op=ita&act=alerts',{signal:badgeRequest.signal,cache:'no-store'}),d=await r.json();
  if(r.ok&&d.success)bell(d.data.active_total);
  }catch{badgeLoaded=false;
  }}
 function activate(){if(!role())return;
  const next=location.hash.slice(1)||'overview';
  const supported=['overview'].includes(next);
  panel.hidden=!supported;
  if(!supported){++sequence;
  request?.abort();
  exportRequest?.abort();
  dispose();
  return;
  }if(next===view&&documentData)return;
  ++sequence;
  request?.abort();
  exportRequest?.abort();
  view=next;
  page=1;
  documentData=null;
  dispose();
  $('dash-output').replaceChildren();
  const support=role()==='support_technician';
  if(support&&next!=='overview'){$('dash-heading').textContent='Không có quyền';
  $('dash-message').textContent='Hỗ trợ chỉ xem bảng bảo trì tại Tổng quan.';
  $('dash-filters').hidden=true;
  $('dash-alert-filters').hidden=true;
  $('dash-export').hidden=true;
  return;
  }$('dash-filters').hidden=false;
  $('dash-heading').textContent=support?'Bảng bảo trì':({overview:'Tổng quan hạ tầng',alerts:'Cảnh báo đang hiệu lực',reports:'Báo cáo'}[view]);
  $('dash-group-field').hidden=support||view!=='overview';
  $('dash-report-field').hidden=view!=='reports';
  $('dash-alert-filters').hidden=view!=='alerts';
  $('dash-year-field').hidden=$('dash-plan-field').hidden=view!=='reports'||$('dash-report').value!=='budget';
  const selected=$('dash-department').value;
  $('dash-department').replaceChildren(new Option('Tất cả trong phạm vi',''),...(window.itaLiveContext.departments||[]).map(d=>new Option(d.label,d.value)));
  $('dash-department').value=selected;
  applied=filters();
  load();
  }
 async function download(format){if(busy||!documentData?.token)return;
  busy=true;
  exportRequest=new AbortController();
  $('dash-xlsx').disabled=$('dash-pdf').disabled=true;
  try{const r=await fetch('/admin.php?op=ita&act=report-export',{method:'POST',signal:exportRequest.signal,headers:{'Content-Type':'application/json','X-CSRF-Token':document.querySelector('meta[name="ita-csrf"]').content},body:JSON.stringify({...applied,format,as_of:documentData.as_of,token:documentData.token})});
  const mime=(r.headers.get('content-type')||'').toLowerCase();
  if(!r.ok||mime.includes('json')){let message='Không thể xuất báo cáo.';
  try{message=(await r.json()).message||message;
  }catch{}throw Error(message);
  }const bytes=new Uint8Array(await r.arrayBuffer());
  const valid=format==='pdf'?mime.includes('application/pdf')&&new TextDecoder().decode(bytes.slice(0,5))==='%PDF-':mime.includes('spreadsheetml')&&bytes[0]===80&&bytes[1]===75;
  if(!valid)throw Error('Phản hồi không phải tệp hợp lệ; chưa tải file.');
  const url=URL.createObjectURL(new Blob([bytes],{type:mime})),a=node('a');
  a.href=url;
  a.download='ita-'+applied.report+'.'+format;
  a.click();
  URL.revokeObjectURL(url);
  $('dash-message').textContent='Đã nhận tệp báo cáo.';
  }catch(e){if(e.name!=='AbortError')$('dash-message').textContent=e.message+' Không tự gửi lại yêu cầu xuất.';
  }finally{busy=false;
  $('dash-xlsx').disabled=$('dash-pdf').disabled=false;
  }}
 $('dash-year').value=new Date().toLocaleDateString('en-CA',{timeZone:'Asia/Ho_Chi_Minh'}).slice(0,4);
 $('dash-filters').addEventListener('submit',e=>{e.preventDefault();
  applied=filters();
  page=1;
  load();
  });
  $('dash-alert-filters').addEventListener('submit',e=>{e.preventDefault();
  applied={...applied,level:$('dash-level').value,reason:$('dash-reason').value,q:$('dash-q').value};
  page=1;
  load();
  });
  $('dash-refresh').addEventListener('click',load);
  $('dash-report').addEventListener('change',()=>{$('dash-year-field').hidden=$('dash-plan-field').hidden=$('dash-report').value!=='budget';
  });
  $('dash-previous').addEventListener('click',()=>{page--;
  load();
  });
  $('dash-next').addEventListener('click',()=>{page++;
  load();
  });
  $('dash-xlsx').addEventListener('click',()=>download('xlsx'));
  $('dash-pdf').addEventListener('click',()=>download('pdf'));
  addEventListener('ita:view',activate);
  addEventListener('ita:data',()=>{if(role()==='support_technician'){document.querySelector('[data-view="alerts"]').hidden=true;
  document.querySelector('[data-view="reports"]').hidden=true;
  $('notification-button').hidden=true;
  $('dash-bell-label').hidden=true;
  }
  activate();
  });
  addEventListener('pageshow',e=>{if(e.persisted){view='';
  activate();
  }});
  addEventListener('pagehide',()=>{++sequence;
  request?.abort();
  exportRequest?.abort();
  badgeRequest?.abort();
  dispose();
  });
  activate();
})();
